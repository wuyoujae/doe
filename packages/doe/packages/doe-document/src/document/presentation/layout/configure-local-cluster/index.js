import { scope as __doeScope } from "../../runtime/context/index.js";

export function configureLocalCluster(node, eligibility, direction) {
    node.kind = "cluster";
    node.layout = {
      ...(node.layout || {}),
      variant: "composition",
      direction,
      ratio: node.layout?.ratio || "auto",
      preset: node.layout?.preset || "local-cluster",
      columns: direction === "row" ? node.children.length : 1,
      maxColumns: __doeScope.MAX_COMPOSITION_ITEMS,
      gap: node.layout?.gap || "12pt",
      align:
        node.layout?.align || (direction === "row" ? "center" : "stretch"),
      origin: "explicit",
      intent: "local-cluster",
      collectionKey: eligibility.collectionKey || null,
      cluster: true,
      keepGroup: true,
      autoGenerated: false,
      textFit: node.layout?.textFit || {
        mode: "readable",
        minBodyPt: __doeScope.MIN_READABLE_FONT_PT,
      },
    };
    return node;
  }
