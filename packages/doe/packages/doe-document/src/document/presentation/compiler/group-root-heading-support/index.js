import { isPrimaryHeadingNode as __doeFn_isPrimaryHeadingNode } from '../is-primary-heading-node/index.js';
import { isHeadingSupportNode as __doeFn_isHeadingSupportNode } from '../is-heading-support-node/index.js';
// Origin: public/yrkie-doe/layout-engine/ai-layout-compiler.js:1841


export function groupRootHeadingSupport(slide, diagnostics) {
    const blocks = Array.isArray(slide.blocks) ? slide.blocks : [];
    const grouped = [];
    for (let index = 0; index < blocks.length; index += 1) {
      const heading = blocks[index];
      const support = blocks[index + 1];
      if (
        !(0, __doeFn_isPrimaryHeadingNode)(heading) ||
        !(0, __doeFn_isHeadingSupportNode)(support) ||
        heading.layout?.lock === "structure" ||
        support.layout?.lock === "structure"
      ) {
        grouped.push(heading);
        continue;
      }
      grouped.push({
        id: `${heading.id || "heading"}-semantic-header`,
        type: "layout-group",
        kind: "cluster",
        layout: {
          variant: "stack",
          direction: "stack",
          columns: 1,
          maxColumns: 1,
          gap: "12pt",
          align: "stretch",
          origin: "explicit",
          intent: "semantic-heading-support",
          cluster: true,
          keepGroup: true,
          autoGenerated: true,
        },
        children: [heading, support],
      });
      diagnostics.push({
        code: "root-heading-support-grouped",
        level: "repair",
        nodeId: heading.id || null,
        message: `${heading.id || "heading"} 与紧邻说明文字已归入语义标题组。`,
      });
      index += 1;
    }
    slide.blocks = grouped;
  }
