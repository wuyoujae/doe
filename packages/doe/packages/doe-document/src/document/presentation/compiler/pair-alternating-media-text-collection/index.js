export function pairAlternatingMediaTextCollection(node, diagnostics) {
    if (!(0, __doeFn_isAlternatingMediaTextCollection)(node)) return node;
    const paired = [];
    for (let index = 0; index < node.children.length; index += 2) {
      const media = node.children[index];
      const text = node.children[index + 1];
      paired.push({
        id: `${node.id}-media-card-${paired.length + 1}`,
        type: "layout-group",
        kind: "cluster",
        layout: {
          variant: "stack",
          direction: "stack",
          ratio: "auto",
          columns: 1,
          maxColumns: 1,
          gap: "12pt",
          align: "stretch",
          origin: "implicit",
          intent: "paired-media-text-card",
          cluster: true,
          keepGroup: true,
          autoGenerated: true,
          textFit: { mode: "readable", minBodyPt: 11, optionalMinBodyPt: 11 },
        },
        children: [media, text],
      });
    }
    node.children = paired;
    node.layout.columns = "auto";
    node.layout.maxColumns = Math.min(
      paired.length,
      Math.max(1, Number(node.layout.maxColumns) || paired.length),
    );
    diagnostics.push({
      code: "alternating-media-text-cards-paired",
      level: "repair",
      nodeId: node.id,
      message: `${node.id} 的交替图片与文字已配对为 ${paired.length} 张自适应卡片。`,
    });
    return node;
  }
