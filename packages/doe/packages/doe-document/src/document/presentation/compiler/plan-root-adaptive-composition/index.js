import { isGroup as __doeFn_isGroup } from '../is-group/index.js';
import { summarize as __doeFn_summarize } from '../summarize/index.js';
import { isSemanticHeaderRegion as __doeFn_isSemanticHeaderRegion } from '../is-semantic-header-region/index.js';
import { containsRootEvidence as __doeFn_containsRootEvidence } from '../contains-root-evidence/index.js';
// Origin: public/yrkie-doe/layout-engine/ai-layout-compiler.js:1940
import { scope as __doeScope } from "../runtime/context/index.js";

export function planRootAdaptiveComposition(slide, diagnostics) {
    const blocks = Array.isArray(slide.blocks) ? slide.blocks : [];
    if (blocks.length < 2 || slide.layout?.preset === "edge-media") return;
    // Explicit columns and full-row notices already define their own reading
    // regions. Root evidence pairing must not absorb them into a composition.
    const requiresOwnRegion = (block) => block.layout?.variant === "columns" ||
      __doeScope.engine.components.get(block.type)?.fullRow ||
      ((0, __doeFn_isGroup)(block) && (block.children || []).some(requiresOwnRegion));
    if (blocks.some(requiresOwnRegion)) return;

    // A flat narrative region followed by one ordinary image is visually a
    // single adaptive composition. Previously these remained independent root
    // flow blocks, so the runtime could only shrink/crop the image after the
    // vertical arrangement overflowed; it had no structural row candidate to
    // evaluate. Wrap the pair as one composition; the V1 solver recognizes
    // its media/narrative relationship and evaluates a row before falling
    // back to the source stack when horizontal room is insufficient.
    const mediaIndexes = blocks
      .map((block, index) =>
        !(0, __doeFn_isGroup)(block) && block.type === "media" ? index : -1,
      )
      .filter((index) => index >= 0);
    const mediaIndex = mediaIndexes[0];
    const narrativeEntries = blocks
      .map((block, index) => ({ block, index, summary: (0, __doeFn_summarize)(block) }))
      .filter((entry) => entry.index !== mediaIndex);
    const canPlanMediaPair =
      mediaIndexes.length === 1 &&
      narrativeEntries.length > 0 &&
      blocks.every(
        (block) => !block.layout?.region && !block.layout?.lock,
      ) &&
      narrativeEntries.every((entry) => entry.summary.role === "flow");
    if (canPlanMediaPair) {
      const narrativeNode =
        narrativeEntries.length === 1
          ? narrativeEntries[0].block
          : {
              id: `${slide.id || "slide"}-narrative-stack`,
              type: "layout-group",
              kind: "cluster",
              layout: {
                variant: "stack",
                direction: "stack",
                columns: 1,
                maxColumns: 1,
                gap: slide.layout?.spacing?.groupGap || "18pt",
                align: "stretch",
                origin: "explicit",
                cluster: true,
                keepGroup: true,
                autoGenerated: true,
              },
              children: narrativeEntries.map((entry) => entry.block),
            };
      const mediaNode = blocks[mediaIndex];
      const children =
        mediaIndex === 0
          ? [mediaNode, narrativeNode]
          : [narrativeNode, mediaNode];
      const adaptiveRoot = {
        id: `${slide.id || "slide"}-adaptive-media`,
        type: "layout-group",
        kind: "container",
        layout: {
          variant: "composition",
          direction: "stack",
          ratio: "auto",
          columns: 1,
          maxColumns: 2,
          gap: slide.layout?.spacing?.groupGap || "18pt",
          align: "stretch",
          origin: "implicit",
          keepGroup: true,
          autoGenerated: true,
          textFit: { mode: "readable", minBodyPt: 11, optionalMinBodyPt: 11 },
        },
        children,
      };
      slide.blocks = [adaptiveRoot];
      diagnostics.push({
        code: "root-media-overflow-axis-planned",
        level: "plan",
        nodeId: adaptiveRoot.id,
        message: `${adaptiveRoot.id} 已启用横排优先、空间不足时回退纵排的根级图文组合。`,
      });
      return;
    }

    const header = (0, __doeFn_isSemanticHeaderRegion)(blocks[0]) ? blocks[0] : null;
    const body = header ? blocks.slice(1) : blocks.slice();
    if (
      body.length < 2 ||
      !body.some(__doeFn_containsRootEvidence) ||
      (body.length === 1 && (0, __doeFn_isGroup)(body[0]))
    ) {
      return;
    }

    const adaptiveBody = {
      id: `${slide.id || "slide"}-adaptive-body`,
      type: "layout-group",
      kind: "container",
      layout: {
        variant: "auto",
        direction: "auto",
        ratio: "auto",
        columns: "auto",
        maxColumns: 4,
        gap: slide.layout?.spacing?.groupGap || "18pt",
        align: "stretch",
        origin: "implicit",
        intent: "root-adaptive-composition",
        autoGenerated: true,
        autoPlan: true,
        textFit: { mode: "readable", minBodyPt: 11, optionalMinBodyPt: 11 },
      },
      children: body,
    };
    slide.blocks = header ? [header, adaptiveBody] : [adaptiveBody];
    diagnostics.push({
      code: "root-evidence-composition-planned",
      level: "plan",
      nodeId: adaptiveBody.id,
      message: `${adaptiveBody.id} 已将平铺的说明与图表内容纳入可重排组合。`,
    });
  }
